// Token Radar model (token-radar-01): snapshot in, ranked board out.
//
// The board ranks ONLY protocols that record no token (no market cap, no
// CoinGecko id, no symbol). It covers every slug on the snapshot's watchlist
// (the floor, never the ceiling) plus every other rankable pre-token protocol
// below the floor. Protocols whose token already trades are kept apart in a
// separate "live" set and are never ranked: the board is a launch radar, not
// a market-cap table. Wrapped, staked, bridged and exchange products are
// excluded outright, because they are a token that already trades in another
// form, not a launch still to come.
//
// Implied value comes only from the snapshot's own figures, through
// scoreProtocol() -> impliedValue():
//
//   base      = tvl_usd * 0.30
//   growth    = clamp(change_7d, -50, +100) per cent; growthMult = 1 + growth/100 * 0.9
//   maturity  = 0.70 + 0.30 * min(age_days, 1460) / 1460   (age unknown: 365 days)
//   breadth   = 1 + 0.04 * min(chains - 1, 8)              (multi-chain reach)
//   category  = tilt by category (see categoryMultiplier): capital-allocator
//               and lending-style protocols carry a premium over plain
//               stablecoin/CDP shells, because a launch reprices the business,
//               not just the deposits
//   implied   = round(base * growthMult * maturity * breadth * category)
//
// No protocol name is ever special-cased: the same function scores every row.
// Farm plans come from farmSteps(): the protocol's own category, chains, TVL
// tier and age decide the action, the capital, the hold and the cost.

export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

export interface ModelConstants {
  base_multiple: number;
  growth_weight: number;
  growth_floor: number;
  growth_cap: number;
  maturity_floor: number;
  maturity_range: number;
  maturity_days: number;
  unknown_age_days: number;
  breadth_per_chain: number;
  breadth_max_chains: number;
}

export const MODEL: ModelConstants = {
  base_multiple: 0.3,
  growth_weight: 0.9,
  growth_floor: -50,
  growth_cap: 100,
  maturity_floor: 0.7,
  maturity_range: 0.3,
  maturity_days: 1460,
  unknown_age_days: 365,
  breadth_per_chain: 0.04,
  breadth_max_chains: 8,
};

export const MODEL_VERSION = 'radar-2';

